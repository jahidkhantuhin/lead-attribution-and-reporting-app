function buildRecordSheet(
  title: string,
  section: LeadSection,
  details: ReturnType<typeof buildLeadReport>['details'],
  player: string,
) {
  const columns = leadColumns(section).filter(
    ({ displayInExcel }) => displayInExcel !== false,
  )
  const records = section === 'all' ? [] : (details[section] ?? [])
  const data =
    section === 'all'
      ? leadRows(details, 'all').map((row) => ({
          ...row,
          type:
            row.kind === 'Call'
              ? 'call'
              : row.kind === 'Chat'
                ? 'chat'
                : row.kind === 'Facebook form'
                  ? 'facebook'
                  : 'email',
          datetime: row.timestamp,
          local_date: row.timestamp,
        }))
      : records.map((row) => tableLeadRecord(row, section))
  return {
    title,
    headings: {
      rowStyle: headerStyle,
      data: columns.map(({ text, styles }) => ({ value: text, styles })),
    },
    content: data.map((row, index) => ({
      rowStyle:
        section.includes('call') ||
        section.includes('chat') ||
        section === 'emails'
          ? { bgColor: leadRowShade(records[index] ?? {}, section) }
          : {},
      data: columns.map((column) => ({
        value: workbookCell(column, row, player) || '',
        styles: column.styles,
      })),
    })),
  }
}

