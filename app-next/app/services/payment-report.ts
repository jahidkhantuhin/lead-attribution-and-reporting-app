import { reportPages } from '~/constants'

export interface RatingRow {
  id: number
  name: string
  total_calls: number | string
  total_call_duration: number | string
  total_rating_time: number | string
}

export interface PaymentReport {
  ratings: RatingRow[]
  pay_rate: number
  cache?: { created_at: string }
}

const columns = [
  { title: 'Client', key: 'name', exportWidth: '25px' },
  { title: 'Calls', key: 'total_calls', exportWidth: '8px' },
  { title: 'Total Call Time', key: 'total_call_duration', exportWidth: '15px' },
  { title: 'Total Rating Time', key: 'total_rating_time', exportWidth: '12px' },
  { title: 'Pay rate', key: 'pay_rate', exportWidth: '10px' },
  { title: 'Total', key: 'total', exportWidth: '10px' },
] as const
export const paymentHeaders = columns.map(({ title, key }) => ({
  title,
  key,
  sortable: false,
}))

function timecode(value: number | string) {
  const seconds = Number.parseInt(String(value), 10)
  const hours = Math.floor(seconds / 3600)
  return [hours, Math.floor(seconds / 60) % 60, seconds % 60]
    .map((part) => String(part).padStart(2, '0'))
    .filter((part, index) => part !== '00' || index > 0)
    .join(':')
}

export function paymentRows(report: PaymentReport) {
  const totals = {
    total_calls: 0,
    total_call_duration: 0,
    total_rating_time: 0,
    total: 0,
  }
  const pay_rate = '$' + report.pay_rate
  const rows = report.ratings.map((rating) => {
    const amount = (
      report.pay_rate *
      (Number(rating.total_rating_time) / 3600)
    ).toFixed(2)
    totals.total_calls += Number(rating.total_calls)
    totals.total_call_duration += Number(rating.total_call_duration)
    totals.total_rating_time += Number(rating.total_rating_time)
    totals.total += Number(amount)
    return {
      ...rating,
      pay_rate,
      total: '$' + amount,
      total_call_duration: timecode(rating.total_call_duration),
      total_rating_time: timecode(rating.total_rating_time),
    }
  })
  const total = {
    id: 'totals',
    name: 'Totals',
    pay_rate,
    total: '$' + totals.total.toFixed(2),
    total_calls: totals.total_calls,
    total_call_duration: timecode(totals.total_call_duration),
    total_rating_time: timecode(totals.total_rating_time),
  }
  return { rows: [...rows, total], total }
}

export function displayDuration(value: string) {
  const units = value.split(':').map(Number)
  const seconds = units.reduce((sum, part) => sum * 60 + part, 0)
  const hours = Math.floor(seconds / 3600)
  const minutes = Math.floor(seconds / 60) % 60
  const remainder = seconds % 60
  if (hours) return `${hours}h ${minutes}m ${remainder}s`
  return minutes
    ? `${minutes}m ${String(remainder).padStart(2, '0')}s`
    : `${remainder}s`
}

export function paymentExport(
  rows: ReturnType<typeof paymentRows>['rows'],
  filters: { scorer: string; from: string; to: string; author: string },
) {
  const title = reportPages.payments.title
  const rowStyle = { width: '30px', textAlign: 'left' }
  return {
    type: 'payment-report',
    name: `${title}, ${filters.scorer}, ${filters.from}-${filters.to}, Generated by ${filters.author}`,
    sheets: [
      {
        title,
        headings: {
          rowStyle: {
            ...rowStyle,
            fontSize: '12px',
            fontWeight: 'bold',
            color: '#f6f6f6',
            bgColor: '#727272',
          },
          data: columns.map(({ title, exportWidth }) => ({
            value: title,
            styles: { width: exportWidth },
          })),
        },
        content: rows.map((item) => ({
          rowStyle: {
            ...rowStyle,
            fontSize: '10px',
            color: item.name === 'Totals' ? '#f6f6f6' : '',
            bgColor: item.name === 'Totals' ? '#727272' : '',
            fontWeight: item.name === 'Totals' ? 'bold' : '',
          },
          data: columns.map(({ key, exportWidth }) => ({
            value: item[key] || '',
            styles: { width: exportWidth },
          })),
        })),
      },
    ],
  }
}
