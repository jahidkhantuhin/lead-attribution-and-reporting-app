import moment from 'moment'
import type { DateRange, Fields, RecordSummary } from '~/types/api'

export interface SiteExtension extends RecordSummary {
  version?: string
  status?: string | number
  is_update_available?: string | number
}
export interface SiteClient extends RecordSummary {
  status?: string
  email?: string
  account_manager_id?: string | number
}
export interface SiteRecord extends RecordSummary {
  url?: string
  siteURL?: string
  wp_version?: string
  site_ip?: string
  status?: number | string
  accountManager?: string | number
  location?: { id: number | string; client?: string | SiteClient }
  plugins?: string | SiteExtension[]
  themes?: SiteExtension[]
  site_information?: Array<{
    url?: string
    staging_url?: string
    registrar?: string
    is_cloudways_hosted?: number
    has_ssl?: string
    created?: string
    expires?: string
  }>
}
export interface SiteDay {
  date: string
  summary: {
    mobile_score?: number
    desktop_score?: number
    mobile_speed_index?: number
    desktop_speed_index?: number
    server_response_time?: number
    desktop_first_contentful_paint?: number
    mobile_first_contentful_paint?: number
  }
}

export const siteColumns = [
  { title: 'Site URL', key: 'siteURL', minWidth: '340px' },
  { title: 'Client Name', key: 'clientName', minWidth: '240px' },
  { title: 'Status', key: 'status', minWidth: '140px' },
  { title: 'Plugins', key: 'plugins', minWidth: '140px' },
  { title: 'Account manager', key: 'accountManager', minWidth: '240px' },
  { title: 'Avg Desktop Score', key: 'avg_desktop_score' },
  { title: 'Avg Desktop Speed Index', key: 'avg_desktop_speed_index' },
  { title: 'Avg Mobile Score', key: 'avg_mobile_score' },
  { title: 'Avg Mobile Speed Index', key: 'avg_mobile_speed_index' },
  { title: 'Avg Server Resp Time', key: 'avg_server_response_time' },
]

export function siteListRow(site: SiteRecord) {
  const client = site.location?.client
  const format = (value: unknown) => (value ? Number(value).toFixed(2) : 0)
  return {
    ...site,
    avg_desktop_score: format(site.avg_desktop_score),
    avg_desktop_speed_index: format(site.avg_desktop_speed_index),
    avg_mobile_score: format(site.avg_mobile_score),
    avg_mobile_speed_index: format(site.avg_mobile_speed_index),
    avg_server_response_time: format(site.avg_server_response_time),
    siteURL: site.url || '',
    clientName: typeof client === 'string' ? client : client?.name || '',
    status: site.status || '',
    accountManager:
      site.accountManager ||
      (typeof client === 'object' ? client.account_manager_id : '') ||
      '',
  }
}

export function buildSiteWorkbook(
  rows: Fields[],
  dates: DateRange,
  author: string,
) {
  const columns = siteColumns.map(({ title, key }) => ({
    title,
    key,
    styles: { width: '20px' },
  }))
  return {
    type: 'SIte-records',
    name: `Site-records, ${moment(dates.date_start).format('YYYY-DD-MM')}-to-${moment(dates.date_end).format('YYYY-DD-MM')}, Generated by ${author}`,
    sheets: [
      {
        title: 'Site Records',
        headings: {
          rowStyle: {
            fontSize: '12px',
            fontWeight: 'bold',
            color: '#f6f6f6',
            bgColor: '#727272',
            width: '30px',
            textAlign: 'left',
          },
          data: columns.map(({ title, styles }) => ({ value: title, styles })),
        },
        content: rows.map((row) => ({
          rowStyle: {},
          data: columns.map(({ key, styles }) => ({
            value: row[key] || '',
            styles,
          })),
        })),
      },
    ],
  }
}

export function siteStatus(value: string | number | undefined) {
  const labels: Record<string, string> = {
    '1': 'Active',
    '0': 'Inactive',
    active: 'Active',
    inactive: 'Inactive',
    paying_client: 'Paying client',
    trial_client: 'Trial client',
    ex_client: 'Former client',
  }
  return labels[String(value)] ?? (value || '—')
}

export function scoreLabel(value: unknown) {
  return value === '' || value == null || !Number.isFinite(Number(value))
    ? '—'
    : Math.round(Number(value))
}
